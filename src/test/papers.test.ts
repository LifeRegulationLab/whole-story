import { PDFDocument } from 'pdf-lib';
import { describe, expect, it } from 'vitest';
import { buildDoc, DOCS, formFor, type PaperInput } from '../lib/papers/documents';
import { pdfSafe, renderPdf } from '../lib/papers/pdf';
import { about, circle, DAY, dose, entry, NOW, prn, regular } from './fixtures';

const input: PaperInput = {
  circle,
  carerName: 'Sam',
  entries: [
    entry({ kind: 'happened', at: NOW - 2 * DAY, areas: ['distress'], needs: ['pain'], flagged: true }),
    entry({ kind: 'night', at: NOW - 3 * DAY, wakings: 3, what: 'Up at 2 and 4.' }),
    entry({ kind: 'health', at: NOW - 4 * DAY, title: 'A fall in the hall', what: 'Found on the floor, no injury seen.', areas: ['moving'] }),
    entry({ kind: 'care-given', at: NOW - DAY, minutes: 90, helpType: 'personal-care', areas: ['washing'], what: 'Help to shower; she cannot stand alone.' }),
  ],
  doses: [dose({ medicineId: 'm1', at: NOW - 2 * DAY, reason: 'agitation', helped: 'yes' })],
  medicines: [prn, regular],
  contacts: [{ id: 'k1', name: 'Dr Patel', role: 'GP', phone: '01234 567890' }],
  papers: [{ id: 'p1', title: 'Lasting power of attorney', kind: 'power-of-attorney', whereKept: 'Blue folder' }],
  about,
  crisis: undefined,
  from: NOW - 30 * DAY,
  to: NOW,
  views: 'She needs someone with her day and night.',
};

/** No tool, AI or clinical-scoring words in anything a carer hands over. */
const FORBIDDEN = /\b(ai|claude|anthropic|chatgpt|openai|generated by|pdf-lib|firebase|score|scored|diagnos\w*)\b|!/i;

describe('documents', () => {
  for (const d of DOCS) {
    it(`builds ${d.kind} from the carer's notes only`, () => {
      const doc = buildDoc(d.kind, input);
      expect(doc.title).toContain('Mum');
      expect(doc.author).toBe('Sam');
      expect(doc.sections.length).toBeGreaterThan(0);
      expect(JSON.stringify(doc)).not.toMatch(FORBIDDEN);
    });
  }

  it('puts the family views first in the CHC pack and chooses no levels', () => {
    const doc = buildDoc('chc', input);
    expect(doc.sections[0]?.heading).toContain('views');
    expect(doc.intro).toContain('has not chosen a level');
  });

  it('picks the benefit form from their age', () => {
    expect(formFor(circle)).toBe('aa');
    expect(formFor({ ...circle, ageBand: 'child' })).toBe('dla');
    expect(formFor({ ...circle, ageBand: 'adult' })).toBe('pip');
    expect(buildDoc('benefits', input).sections.some((s) => s.heading === 'Caring hours written down')).toBe(true);
  });

  it('marks notes written more than a day late', () => {
    const late = { ...input, entries: [entry({ kind: 'happened', at: NOW - 5 * DAY, writtenAt: NOW - DAY, areas: ['distress'] })] };
    expect(JSON.stringify(buildDoc('chc', late))).toContain('(written');
  });
});

describe('pdf', () => {
  it('makes a PDF with the carer as author and no tool names', async () => {
    const bytes = await renderPdf(buildDoc('respite', input), new Date(NOW));
    const pdf = await PDFDocument.load(bytes, { updateMetadata: false });
    expect(pdf.getAuthor()).toBe('Sam');
    expect(pdf.getProducer()).toBe('Whole Story by Life Regulation Lab');
    expect(pdf.getCreator()).toBe('Whole Story by Life Regulation Lab');
    expect(pdf.getPageCount()).toBeGreaterThan(0);
    const raw = new TextDecoder('latin1').decode(bytes);
    expect(raw).not.toMatch(/pdf-lib|Claude|Anthropic/i);
  });

  it('copes with characters the standard fonts lack', async () => {
    expect(pdfSafe('It’s “fine” – really… 😀')).toBe('It\'s "fine" - really...');
    const doc = buildDoc('about-me', { ...input, about: { ...about, sections: { life: 'Zoë loves 🌻 and café trips' } } });
    await expect(renderPdf(doc)).resolves.toBeInstanceOf(Uint8Array);
  });
});
